/**
 * Generate full table (256 * 16 values)
 */
function generateTable() {
    const fullTable = new Int8Array(256 * 16);

    // Fill first 128
    for (let i = 0; i < triTablePartial.length; i++) {
        fullTable[i] = triTablePartial[i];
    }

    // Generate 128-255 by symmetry
    for (let i = 128; i < 256; i++) {
        const srcIdx = 255 - i;
        const offset = srcIdx * 16;
        const destOffset = i * 16;

        // Read tris
        const tris = [];
        for (let j = 0; j < 16; j++) {
            tris.push(fullTable[offset + j]);
        }

        // Reverse winding for invert
        const finalTris = new Array(16).fill(-1);
        let t = 0;
        while (t < 16 && tris[t] !== -1) {
            finalTris[t] = tris[t];
            finalTris[t + 1] = tris[t + 2];
            finalTris[t + 2] = tris[t + 1];
            t += 3;
        }

        for (let j = 0; j < 16; j++) {
            fullTable[destOffset + j] = finalTris[j];
        }
    }

    return fullTable;
}

